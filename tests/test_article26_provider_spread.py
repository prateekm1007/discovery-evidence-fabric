"""Constitution v3.0.0, Article 26 — Provider spread (CI).

"No substance claim without at least 2 providers and a judge
different from every generator. Failures are never cached."

Runs on the COMMITTED battery records (real bytes): battery r11
(battery_a1w_r11.json) and battery r10 (battery_a1t_r10.json).

Checks:
  1. judge != every generator — the recorded judge route (provider,
     model) must differ from the A-arm generator provider/model
     resolved from the pair record of the same problem.
  2. >= 2 providers involved per substance claim — the loop is
     provider-spanned: a zai/GLM generator judged by a crowllm/Qwen
     judge (2 distinct providers); the B arm is CURATED standard
     practice text (no provider claim — disclosed: it is not
     provider-generated, so the 2-provider requirement is met by the
     generator+judge pair, not by two generators).
  3. every valid row carries k=3 judge draws.
  4. no cached failures — no two draws of a row carry an identical
     raw payload (identical bytes would indicate a cached/held
     response, not fresh inference).
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

BATTERIES = [REPO / "eval" / "battery_a1w_r11.json",
             REPO / "eval" / "battery_a1t_r10.json"]
ARMS = [REPO / "eval" / "pairs" / "r11_a1w_r1",
        REPO / "eval" / "pairs" / "r11_a1t_r1"]
K = 3


def _generator_provider(pid):
    for arm in ARMS:
        f = arm / f"{pid}.json"
        if f.exists():
            rec = json.loads(f.read_text())
            gen = str(rec.get("generator") or "")
            src = str(rec.get("a1_source") or "")
            # provider = the token before '/' in the model id, or the
            # gateway name; zai/GLM records identify both
            if "zai" in gen.lower() or "GLM" in src.upper():
                return ("zai", gen)
            for prov in ("openai", "anthropic", "crowllm", "openrouter"):
                if prov in gen.lower():
                    return (prov, gen)
            return ("unknown", gen)
    return ("missing", "")


def test_article26_judge_differs_from_every_generator():
    flagged = []
    for bf in BATTERIES:
        rec = json.loads(bf.read_text())
        for r in rec.get("results", []):
            judge = r.get("judge") or []
            if len(judge) != 2:
                flagged.append(f"{bf.name}/{r['problem_id']}: judge route "
                               f"not (provider, model): {judge!r}")
                continue
            jprov, jmodel = str(judge[0]).lower(), str(judge[1]).lower()
            gprov, gdesc = _generator_provider(r["problem_id"])
            if gprov == "missing":
                flagged.append(f"{bf.name}/{r['problem_id']}: no pair "
                               f"record for the A arm")
                continue
            if gprov == "unknown":
                flagged.append(f"{bf.name}/{r['problem_id']}: generator "
                               f"provider unidentifiable: {gdesc[:60]!r}")
                continue
            if gprov == jprov or gprov in jmodel or jprov in gdesc.lower():
                flagged.append(
                    f"{bf.name}/{r['problem_id']}: judge == generator "
                    f"(judge={jprov}/{jmodel}, gen={gprov})")
    assert not flagged, (
        "Art. 26 judge/generator separation violated on committed "
        "bytes: " + "; ".join(flagged[:8]))


def test_article26_two_distinct_providers_per_claim():
    # the loop's substance outputs (A-arm answers) are generated by
    # one provider and judged by a different one -> >=2 providers
    providers = set()
    for bf in BATTERIES:
        rec = json.loads(bf.read_text())
        rows = rec.get("results", [])
        assert rows, f"{bf.name}: no rows"
        j = rows[0].get("judge") or []
        providers.add(str(j[0]).lower())
        gprov, _ = _generator_provider(rows[0]["problem_id"])
        providers.add(gprov)
    assert "unknown" not in providers and "missing" not in providers
    assert len(providers) >= 2, (
        f"Art. 26 provider spread violated: {providers!r}")


def test_article26_k3_draws_and_no_cached_failures():
    flagged = []
    for bf in BATTERIES:
        rec = json.loads(bf.read_text())
        for r in rec.get("results", []):
            draws = r.get("draws", [])
            if len(draws) != K:
                flagged.append(f"{bf.name}/{r['problem_id']}: "
                               f"{len(draws)} draws != k=3")
            raws = [str(d.get("axes") if d.get("axes") is not None
                        else d.get("outcome")) for d in draws]
            if len(set(raws)) != len(raws):
                # identical full axes+outcome across all draws is the
                # cache signature; check the full payload equality
                full = [json.dumps(d, sort_keys=True) for d in draws]
                if len(set(full)) != len(full):
                    flagged.append(
                        f"{bf.name}/{r['problem_id']}: identical draw "
                        f"payloads (cached response suspected)")
    assert not flagged, ("Art. 26 draw/cache violation: "
                         + "; ".join(flagged[:8]))
