"""tests/test_r535_dependency_failure_injection.py — R535 audit §5.

Real EngineRun conductor failure-injection tests for the critical
seams named by the R535 §5 directive:

  FREEZE failure
  SYNTHESIZE failure (R533-pinned path, re-guarded here)
  VERIFY failure
  COLLISION failure
  ATTACK failure
  RETRIEVE failure (the R534 closed defect — regression guard)

For each injection we assert:
  1. the injected stage records its own typed failure/skip state;
  2. every downstream stage in its declared DOWNSTREAM_BLOCKERS set
     records a typed skip (never a false OK on empty input);
  3. no blocked stage emits status=OK;
  4. the run terminates in a typed NON-discovery state (Art.
     LXXVII: no survivor credit on a mid-chain failure).

The authoritative machine record of this trace is
R535/DEPENDENCY_INJECTION_TRACE.json (generated by
scripts/r535_run_injection_trace.py); this pytest file is the
regression guard that re-drives the same conductor paths.

Seam-isolation note: the hermetic test env has no LLM providers, so
SYNTHESIZE / MECHANISM_SPACE real executes would fail on
PROVIDER_UNAVAILABLE before the injected stage is reached.  To
isolate the injected seam's CONDUCTOR response, upstream LLM
stages are stubbed to a deterministic typed OK (their real code
path is not the object under test — the conductor's skip-cascade
and typed-state recording are).
"""
from __future__ import annotations

import sys
import unittest
from pathlib import Path
from unittest.mock import patch

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from discovery_fabric.engine import adapters as ad  # noqa: E402
from discovery_fabric.engine.run import (  # noqa: E402
    EngineRun, DOWNSTREAM_BLOCKERS, FATAL_STAGES)
import discovery_fabric.evidence_fabric as _ef_mod  # noqa: E402

# Typed non-discovery terminal states (Art. LXXVII: none of these is
# a survivor/package credit).
NON_DISCOVERY_TERMINALS = frozenset({
    "UNKNOWN", "MECHANISM_GENERATION_FAILED",
    "MALFORMED_OR_FALSE_PREMISE",
    "PROBLEM_EXISTENCE_UNESTABLISHED",
    "PIPELINE_FAILED",
})


def _problem():
    return {"problem_id": "r535-injection",
            "device": "tunneled hemodialysis catheter",
            "failure_mode": "OCCLUSION",
            "failure": "catheter occlusion",
            "constraint": "x"}


