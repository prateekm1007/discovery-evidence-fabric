    print(f"    Adversarial terms: {adv_discovered}/{len(truth['adversarial_terms'])} ({adv_discovered/len(truth['adversarial_terms']):.0%})")
    if adv_missed:
        print(f"    MISSED adversarial: {adv_missed}")
    print()


