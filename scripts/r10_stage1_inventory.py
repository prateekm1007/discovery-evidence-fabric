#!/usr/bin/env python3
"""r10_stage1_inventory.py — AM10 D1 stage 1: typed inventory of the
30-pair battery state at 9570c4bc1 (committed bytes vs missing bytes,
generator confound map, judge miscalibration data). Committed+pushed as
its OWN stage before any re-generation work starts (Art. LXXIV/LXXXV)."""
import datetime
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BAT = REPO / "eval" / "battery_peraxis_r11_r6.json"
PAIRS = REPO / "eval" / "pairs" / "r11_a1_r3"
now = datetime.datetime.now(datetime.UTC).isoformat().replace("+00:00", "Z")

d = json.loads(BAT.read_text())
committed, missing = [], []
for p in d["results"]:
    pid = p["problem_id"]
    if p["a1_source"].startswith("PROMOTED_DELIVERY"):
        f = PAIRS / f"{pid}.json"
        has_bytes = f.exists() and bool(
            json.loads(f.read_text()).get("a1_answer", "").strip())
        (committed if has_bytes else missing).append(
            {"problem_id": pid, "a1_source": p["a1_source"],
             "bytes_on_disk": has_bytes})
    else:
        missing.append({"problem_id": pid, "a1_source": p["a1_source"],
                        "bytes_on_disk": False,
                        "missing": "axes+prompt_hash only (F29)"})

rec = {
    "record": "r10_stage1_inventory/1.0.0",
    "at": now,
    "basis_sha": "9570c4bc1",
    "n_pairs": len(d["results"]),
    "committed_a1_bytes": committed,
    "missing_a1_bytes": missing,
    "n_committed": len(committed),
    "n_missing": len(missing),
    "f29_generator_confound": {
        "finding": "18 fresh A1 answers generated by raw mistral-14b "
                   "(not the curated GLM generator) and never committed "
                   "as bytes — auditor cannot re-judge them (Art. 1/LXII)",
        "plan": "re-generate all 18 with the curated GLM generator "
                "(zai gateway, zai-org/GLM-5.3, SYS_A1 label contract), "
                "bytes committed incrementally per batch as "
                "eval/pairs/r11_a1_fresh_r10/<pid>.json with "
                "a1_source=GLM_CURATED_R10_REGEN",
    },
    "f28_judge_miscalibration": {
        "judge": d.get("judge"),
        "measured": "bench-p02 novelty REVERSED (standard baseline 3 > "
                    "pure-Sn plating A1 2); feasibility_a1=1 vs auditor 3; "
                    "kappa 0.40 < 0.6; dev12-subset divergence: qwen "
                    "novelty 1.38/feasibility 1.69 vs auditor 0.8/0.5 on "
                    "the SAME committed answers (r9 assessment)",
        "plan": "recalibrate the per-axis judge on the auditor's "
                "per-axis labels (r5 10-pair full-axis scores + r6 "
                "draft scores): reproduce the defect on the current "
                "prompt, add calibrated axis anchors, re-measure to "
                "kappa>=0.6 + novelty sign agreement >=0.8 + bench-p02 "
                "corrected; adversarial gold-set check must still "
                "separate good from bad (Art. XXX)",
    },
    "current_gate_inputs_under_qwen": {
        "novelty_delta_mean": 2.467, "novelty_ci": [1.797, 3.136],
        "feasibility_gap_mean": 2.0, "feasibility_ci": [1.549, 2.451],
        "note": "miscalibrated judge — neither number is authoritative "
                "(F28); the recalibrated judge re-measures on committed "
                "bytes",
    },
    "stage_plan": [
        "stage 1: this inventory (committed)",
        "stage 2: judge recalibration corpus + measured defect "
        "reproduction (committed)",
        "stage 3: calibrated judge prompt + re-measure to acceptance "
        "(committed)",
        "stage 4: GLM re-generation of the 18 fresh A1 answers, "
        "bytes committed per batch",
        "stage 5: feasibility-grounding leg on the 30 answers "
        "(committed per batch)",
        "stage 6: per-axis re-judgment on committed bytes + gate-input "
        "recompute (committed); auditor re-judgment n=30 follows "
        "(AM10 D5)",
    ],
}
out = REPO / "eval" / "r10_stage1_inventory.json"
out.write_text(json.dumps(rec, indent=1, ensure_ascii=False) + "\n",
               encoding="utf-8")
print(f"[s1] committed={len(committed)} missing={len(missing)} "
      f"-> {out.name}")
for m in missing:
    print("  missing:", m["problem_id"])
