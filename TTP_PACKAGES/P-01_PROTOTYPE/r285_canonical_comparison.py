def get_file_hash(filepath):
    """Get SHA-256 hash of a file for provenance."""
    h = hashlib.sha256()
    with open(filepath, 'rb') as f:
        while True:
            chunk = f.read(8192)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def run_one(arm, seed, attack):
    """Run one simulation using the SAME framework for all arms."""
    # All arms use the V2 full validation framework for consistency
    # D_V2_1 uses the V2.1 controller (sensor-health-aware)
    # A/B/C use the V2 framework controllers

    if arm == "D_V2_1":
        # V2.1 controller — uses 14_V2_1_validation.py's run_v2_1
        r = _v21.run_v2_1("C_V2", seed, attack)
        r["scenario"] = "D_V2_1"
        return r

    # A, B, C use the V2 framework (12_V2_full_validation.py)
    cfg = _v2f.make_cfg(arm, seed, attack)
    r = _v2f.run_v2_full(cfg)
    return {
        "scenario": arm,
        "seed": seed,
        "attack_mode": attack,
        "metric_1_peak_icp_mmhg": r.metric_1_peak_icp_mmhg,
        "metric_2_time_above_threshold_sec": r.metric_2_time_above_threshold_sec,
        "metric_3_time_to_critical_failure_hr": r.metric_3_time_to_critical_failure_hr,
        "metric_4_drainage_preserved_percent": r.metric_4_drainage_preserved_percent,
        "metric_5_false_interventions": r.metric_5_false_interventions,
        "metric_6_actuation_count": r.metric_6_actuation_count,
        "metric_7_energy_arbitrary_units": r.metric_7_energy_arbitrary_units,
        "survival": r.survival,
    }


def main():
    # Record provenance metadata
    sim_file_12 = os.path.join(HERE, "12_V2_full_validation.py")
    sim_file_14 = os.path.join(HERE, "14_V2_1_validation.py")
    provenance = {
        "experiment": "R285 CANONICAL DECISIVE COMPARISON",
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "simulator_files": {
            "12_V2_full_validation.py": get_file_hash(sim_file_12),
            "14_V2_1_validation.py": get_file_hash(sim_file_14),
        },
        "seeds": SEEDS,
        "attacks": ATTACKS,
        "arms": ARMS,
        "total_runs": len(ARMS) * len(ATTACKS) * len(SEEDS),
        "success_criteria": SUCCESS_CRITERIA,
        "data_reuse": "NONE — all 180 runs generated fresh by this script",
    }

    print("=" * 110)
    print("R285 CANONICAL DECISIVE COMPARISON")
    print("Single immutable runner. No data reuse. 180 runs.")
    print("=" * 110)
    print(f"Simulator hashes: 12_V2={provenance['simulator_files']['12_V2_full_validation.py'][:16]}... 14_V2_1={provenance['simulator_files']['14_V2_1_validation.py'][:16]}...")
    print(f"Total runs: {provenance['total_runs']}")
    print()

    # Load existing if any (for incremental save/resume)
    existing = []
    if os.path.exists(OUTPUT):
        with open(OUTPUT) as f:
            data = json.load(f)
        if "results" in data:
            existing = data["results"]
    existing_keys = set((r["scenario"], r["seed"], r["attack_mode"]) for r in existing)

    total = provenance["total_runs"]
    done = len(existing)
    print(f"Progress: {done}/{total}")

    for arm in ARMS:
        for attack in ATTACKS:
            for seed in SEEDS:
                key = (arm, seed, attack)
                if key in existing_keys:
                    continue
                r = run_one(arm, seed, attack)
                existing.append(r)
                existing_keys.add(key)
                done += 1
                if done % 10 == 0:
                    print(f"  [{done}/{total}] {arm} seed={seed} {attack}: t_fail={r.get('metric_3_time_to_critical_failure_hr', '?')}h")
                    # Save incrementally
                    with open(OUTPUT, 'w') as f:
                        json.dump({"provenance": provenance, "results": existing}, f, indent=2)

    # Final save
    with open(OUTPUT, 'w') as f:
        json.dump({"provenance": provenance, "results": existing}, f, indent=2)
    print(f"\nCOMPLETE: {len(existing)}/{total} runs saved to {OUTPUT}")

    # Analysis
    print("\n" + "=" * 110)
    print("CANONICAL DECISIVE COMPARISON: V2.1 (D) vs B")
    print("=" * 110)
    print(f"{'Attack':<22} {'B t_fail':<10} {'V2.1 t_fail':<12} {'V2.1/B':<8} {'B peak':<10} {'V2.1 peak':<10} {'wins':<8} {'Verdict':<15}")
    print("-" * 110)

    v21_wins = 0
    for attack in ATTACKS:
        b_runs = [r for r in existing if r["scenario"] == "B_predictive_closed_loop" and r["attack_mode"] == attack]
        d_runs = [r for r in existing if r["scenario"] == "D_V2_1" and r["attack_mode"] == attack]
        if not b_runs or not d_runs:
            continue
        b_tfail = sum(r["metric_3_time_to_critical_failure_hr"] for r in b_runs) / len(b_runs)
        d_tfail = sum(r["metric_3_time_to_critical_failure_hr"] for r in d_runs) / len(d_runs)
        b_peak = sum(r["metric_1_peak_icp_mmhg"] for r in b_runs) / len(b_runs)
        d_peak = sum(r["metric_1_peak_icp_mmhg"] for r in d_runs) / len(d_runs)
        ratio = d_tfail / max(b_tfail, 0.01)
        d_wins_seeds = sum(1 for b, d in zip(sorted(b_runs, key=lambda r: r["seed"]),
                                              sorted(d_runs, key=lambda r: r["seed"]))
                          if d["metric_3_time_to_critical_failure_hr"] > b["metric_3_time_to_critical_failure_hr"])
        d_better = (d_tfail > b_tfail * 1.10) and (d_peak <= b_peak * 1.1) and (d_wins_seeds >= 4)
        if d_better:
            verdict = "V2.1 BETTER"
            v21_wins += 1
        elif d_tfail > b_tfail:
            verdict = "V2.1 marginal"
        else:
            verdict = "V2.1 WORSE"
        print(f"{attack:<22} {b_tfail:<10.2f} {d_tfail:<12.2f} {ratio:<8.2f} {b_peak:<10.1f} {d_peak:<10.1f} {d_wins_seeds}/5{'':<3} {verdict:<15}")

    print(f"\nV2.1 materially outperforms B on {v21_wins}/{len(ATTACKS)} attack modes (CANONICAL, single experiment).")

    # Primary endpoint check
    print("\n" + "=" * 110)
    print("PRE-REGISTERED PRIMARY ENDPOINT CHECK")
    print("=" * 110)
    b_noise3 = [r for r in existing if r["scenario"] == "B_predictive_closed_loop" and r["attack_mode"] == "noise_3x"]
    d_noise3 = [r for r in existing if r["scenario"] == "D_V2_1" and r["attack_mode"] == "noise_3x"]
    if b_noise3 and d_noise3:
        b_mean = sum(r["metric_3_time_to_critical_failure_hr"] for r in b_noise3) / len(b_noise3)
        d_mean = sum(r["metric_3_time_to_critical_failure_hr"] for r in d_noise3) / len(d_noise3)
        ratio = d_mean / max(b_mean, 0.01)
        wins = sum(1 for b, d in zip(sorted(b_noise3, key=lambda r: r["seed"]),
                                      sorted(d_noise3, key=lambda r: r["seed"]))
                   if d["metric_3_time_to_critical_failure_hr"] > b["metric_3_time_to_critical_failure_hr"])
        print(f"B mean t_fail (noise_3x): {b_mean:.2f}h")
        print(f"V2.1 mean t_fail (noise_3x): {d_mean:.2f}h")
        print(f"V2.1/B ratio: {ratio:.2f}x (threshold >= 2.0x) → {'PASS' if ratio >= 2.0 else 'FAIL'}")
        print(f"V2.1 wins: {wins}/5 seeds (threshold >= 4) → {'PASS' if wins >= 4 else 'FAIL'}")

    print(f"\nProvenance saved with results. Data reuse: NONE.")


if __name__ == "__main__":
    main()
