def new_pathway_entry(*, entry_id, territory_id, mechanism_name,
                      proposed_version, kill_reason, why_it_failed,
                      evidence_sources, attack_results, kill_condition,
                      reusable_lesson=None, what_to_avoid=None,
                      epistemic_class=None) -> dict:
    """The six-element pathway shape every NEW cemetery entry must carry
    (used by the repo-rule applier). All six elements structural —
    legacy honesty markers are not permitted for new entries."""
    return {
        "entry_id": entry_id,
        "territory_id": territory_id,
        "mechanism_name": mechanism_name,
        "proposed_version": proposed_version,
        "kill_reason": kill_reason,
        "why_it_failed": why_it_failed,
        "evidence_sources": evidence_sources,
        "attack_results": attack_results,
        "kill_condition": kill_condition,
        "reusable_lesson": reusable_lesson,
        "what_to_avoid": what_to_avoid,
        "epistemic_class": epistemic_class,
        "pathway": {
            "CANDIDATE": {"territory_id": territory_id,
                          "mechanism_name": mechanism_name,
                          "proposed_version": proposed_version},
            "FAILURE_REASON": {"kill_reason": kill_reason,
                               "why_it_failed": why_it_failed},
            "EVIDENCE": {"evidence_sources": evidence_sources},
            "ATTACK_RESULTS": {"state": "STRUCTURED",
                               "value": attack_results},
            "KILL_CONDITION": {"value": kill_condition,
                               "derivation": "recorded structured field"},
            "CEMETERY": {"entry_id": entry_id, "append_only": True,
                         "note": "the cemetery entry is the record; "
                                 "nothing is deleted (CEO R374-6)"},
        },
    }
