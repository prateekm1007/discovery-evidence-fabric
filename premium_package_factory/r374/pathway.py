"""
pathway.py — CEO R374-6: preserve the failed-candidate pathway.

Required pathway for ANY candidate generated by the discovery engine
that fails:

    CANDIDATE -> FAILURE REASON -> EVIDENCE -> ATTACK RESULTS ->
    KILL CONDITION -> CEMETERY

Rules:
  * Nothing is deleted. The cemetery is append-only: no entry may ever
    disappear (mechanically verified against git history), and
    entry_count never decreases.
  * Legacy entries (26 at R374 time) predate the structured schema.
    Their pathway is re-presented from RECORDED fields only:
    KILL_CONDITION is derived from the recorded kill_reason (+ recorded
    physical_constraint where present) and marked as a derivation —
    never as new evidence; ATTACK_RESULTS that were never structured
    are marked NOT_STRUCTURED with the reason. Nothing is fabricated
    (Constitution Art. VI).
  * Future failures (the repo-rule applier) must emit all six elements
    structurally: new_pathway_entry() is the required shape.
"""

import json
import os
import subprocess

PATHWAY_ELEMENTS = ("CANDIDATE", "FAILURE_REASON", "EVIDENCE",
                    "ATTACK_RESULTS", "KILL_CONDITION", "CEMETERY")

PATHWAY_SCHEMA = {
    "CANDIDATE": "territory_id + mechanism_name + proposed_version — "
                 "what was generated and proposed",
    "FAILURE_REASON": "kill_reason (class) + why_it_failed (recorded "
                      "detail)",
    "EVIDENCE": "evidence_sources — the artifacts that document the "
                "failure",
    "ATTACK_RESULTS": "structured adversarial-attack outcomes that "
                      "contributed to (or were run against) the candidate; "
                      "legacy entries without structured results carry "
                      "state NOT_STRUCTURED honestly",
    "KILL_CONDITION": "the explicit condition under which the candidate "
                      "is dead (derived for legacy entries from the "
                      "recorded kill_reason / physical_constraint — "
                      "marked as derived, never invented)",
    "CEMETERY": "entry_id + append-only residency; the entry is the "
                "record, so removal is forbidden",
}


# ---------------------------------------------------------------------------
# per-entry pathway (re-presentation of recorded data — no invention)
# ---------------------------------------------------------------------------

def _kill_condition_of(entry: dict) -> dict:
    """Explicit kill condition: from the structured field when present;
    for legacy entries, re-presented from recorded fields and MARKED as
    a derivation."""
    if entry.get("kill_condition"):
        return {"value": entry["kill_condition"],
                "derivation": "recorded structured field"}
    parts = [str(entry.get("kill_reason") or "").strip()]
    pc = entry.get("physical_constraint")
    if pc:
        parts.append(f"physical constraint: {pc}")
    value = "; ".join(p for p in parts if p and p != "None")
    if not value:
        return {"value": None, "derivation": "NOT_RECORDED"}
    return {"value": value,
            "derivation": "re-presented from the recorded kill_reason "
                          "(+ physical_constraint where present) — "
                          "R374-6 schema, not new evidence"}


def _attack_results_of(entry: dict) -> dict:
    ar = entry.get("attack_results")
    if ar in (None, "", [], {}):
        narrative = " ".join(
            str(entry.get(k) or "") for k in
            ("why_it_failed", "what_to_avoid", "reusable_lesson"))
        had_attacks = "attack" in narrative.lower()
        return {
            "state": "NOT_STRUCTURED",
            "reason": (
                "legacy entry predates the structured attack-results "
                "field; " +
                ("attack narrative is embedded in why_it_failed — "
                 "re-presented there, not restructured (Art. VI)"
                 if had_attacks else
                 "no attack-stage result recorded for this entry — not "
                 "fabricated")),
        }
    return {"state": "STRUCTURED", "value": ar}


def entry_pathway(entry: dict) -> dict:
    """The six-element pathway of one cemetery entry, re-presented from
    recorded fields."""
    return {
        "CANDIDATE": {
            "territory_id": entry.get("territory_id"),
            "mechanism_name": entry.get("mechanism_name"),
            "proposed_version": entry.get("proposed_version"),
        },
        "FAILURE_REASON": {
            "kill_reason": entry.get("kill_reason"),
            "why_it_failed": entry.get("why_it_failed"),
        },
        "EVIDENCE": {
            "evidence_sources": entry.get("evidence_sources"),
        },
        "ATTACK_RESULTS": _attack_results_of(entry),
        "KILL_CONDITION": _kill_condition_of(entry),
        "CEMETERY": {
            "entry_id": entry.get("entry_id"),
            "append_only": True,
            "note": "the cemetery entry is the record; nothing is "
                    "deleted (CEO R374-6)",
        },
    }


def audit_entry_pathway(entry: dict) -> dict:
    """Mechanical completeness audit of one entry's pathway."""
    problems = []
    missing_elements = []
    cand = entry.get("pathway", {}).get("CANDIDATE", {})
    if not (cand.get("territory_id") and cand.get("mechanism_name")):
        problems.append("CANDIDATE incomplete")
        missing_elements.append("CANDIDATE")
    fr = entry.get("pathway", {}).get("FAILURE_REASON", {})
    if not (fr.get("kill_reason") or fr.get("why_it_failed")):
        problems.append("FAILURE_REASON absent")
        missing_elements.append("FAILURE_REASON")
    ev = entry.get("pathway", {}).get("EVIDENCE", {})
    if not ev.get("evidence_sources"):
        problems.append("EVIDENCE absent")
        missing_elements.append("EVIDENCE")
    ar = entry.get("pathway", {}).get("ATTACK_RESULTS", {})
    if not ar.get("state"):
        problems.append("ATTACK_RESULTS unclassified")
        missing_elements.append("ATTACK_RESULTS")
    kc = entry.get("pathway", {}).get("KILL_CONDITION", {})
    if not kc.get("value"):
        problems.append("KILL_CONDITION absent")
        missing_elements.append("KILL_CONDITION")
    cem = entry.get("pathway", {}).get("CEMETERY", {})
    if not cem.get("entry_id"):
        problems.append("CEMETERY entry_id absent")
        missing_elements.append("CEMETERY")
    return {
        "entry_id": entry.get("entry_id"),
        "elements_present": [e for e in PATHWAY_ELEMENTS
                             if e not in missing_elements],
        "problems": problems,
        "complete": not problems,
    }


